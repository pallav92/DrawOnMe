package com.draw.onme.domain.model

import kotlin.math.cos
import kotlin.math.hypot
import kotlin.math.sin

/**
 * Picks where to print every region's number on a page, keeping labels apart even when several
 * regions share (or nearly share) a center - concentric rings, a cluster of small decorations
 * near one spot, and so on - keeping every label off the drawn outline strokes themselves
 * (including decorative detail lines, like pupils or whiskers, that sit inside a region but
 * aren't region boundaries), and - just as important - never printing a region's number over a
 * spot that actually belongs to a *different* region.
 *
 * Regions can geometrically overlap on purpose: a concentric inner ring's polygon sits inside its
 * outer ring's polygon, and two unrelated parts (say a vehicle's hood and its main body shell)
 * can share territory where one is simply drawn on top of the other. [ColoringViewModel]'s tap
 * handling resolves an overlap by hit-testing every region containing the tapped point and
 * picking the smallest one - so a point inside both the body and the hood always means "hood".
 * A label must respect that same rule: a point inside region A's boundary that's *also* inside a
 * smaller region B is actually B's territory (visually, since B renders on top, and functionally,
 * since tapping there fills B) - printing A's number there is both confusing and wrong, since
 * tapping the number itself would color the wrong region. See [isOwned].
 *
 * Approach: for every region, first find an "anchor" point inside its own boundary that the
 * region actually owns (no smaller region claims it) and that sits as far as possible from every
 * outline stroke on the page - a spot naturally clear of lines and of neighboring territory, not
 * just the polygon centroid (which can be on a decorative line, or claimed by a nested region).
 * Start each label at its anchor, then run a short physics-style relaxation that pushes any pair
 * of labels closer than [MIN_SEPARATION] apart, repeating until the page settles or the iteration
 * budget runs out. Finally each label is pulled back toward its anchor if the relaxation pushed it
 * outside its own territory - a region too small or too crowded to fit full clearance just ends up
 * back at its anchor, the best any approach can do for a sliver of a shape.
 */
internal object RegionLabelPlacement {

    // Minimum normalized distance kept between any two labels on the same page - tuned to the
    // font sizes RegionLabelFontSize hands out, so two single/double-digit numbers clear each
    // other by a comfortable margin at the sizes actually rendered.
    private const val MIN_SEPARATION = 0.045f

    // Minimum normalized distance kept between a label and any drawn outline stroke (a region
    // boundary or a decorative detail line), so numbers don't print on top of ink.
    private const val MIN_LINE_DISTANCE = 0.022f

    private const val ITERATIONS = 60

    // Resolution of the grid search used to find each region's anchor point (the spot inside its
    // boundary farthest from every outline). Higher is more precise but costs more work; this is
    // computed once per page, so a modest grid is plenty.
    private const val ANCHOR_GRID_STEPS = 10

    // Golden-angle based per-index offset, used only to break a perfect tie (anchors that are
    // *exactly* coincident, e.g. a concentric ring generated by scaling the same boundary) so the
    // relaxation below has a direction to push in rather than dividing by a zero-length vector.
    private const val GOLDEN_ANGLE_RADIANS = 2.399963f
    private const val TIE_BREAK_NUDGE = 0.0005f

    private fun centroidOf(points: List<Point>): Point {
        if (points.isEmpty()) return Point(0f, 0f)
        val cx = points.sumOf { it.x.toDouble() }.toFloat() / points.size
        val cy = points.sumOf { it.y.toDouble() }.toFloat() / points.size
        return Point(cx, cy)
    }

    private fun distance(a: Point, b: Point): Float =
        hypot((a.x - b.x).toDouble(), (a.y - b.y).toDouble()).toFloat()

    private fun distanceToSegment(p: Point, a: Point, b: Point): Float {
        val abx = b.x - a.x
        val aby = b.y - a.y
        val lengthSq = abx * abx + aby * aby
        if (lengthSq < 1e-12f) return distance(p, a)
        val t = (((p.x - a.x) * abx + (p.y - a.y) * aby) / lengthSq).coerceIn(0f, 1f)
        return distance(p, Point(a.x + abx * t, a.y + aby * t))
    }

    private fun segmentsOf(outline: ColoringOutline): List<Pair<Point, Point>> {
        val points = outline.points
        if (points.size < 2) return emptyList()
        val segments = points.zipWithNext().toMutableList()
        if (outline.isClosed) segments += points.last() to points.first()
        return segments
    }

    private fun polygonSegments(boundary: List<Point>): List<Pair<Point, Point>> {
        if (boundary.size < 2) return emptyList()
        return boundary.zipWithNext() + (boundary.last() to boundary.first())
    }

    private fun minDistanceToSegments(point: Point, segments: List<Pair<Point, Point>>): Float {
        var best = Float.MAX_VALUE
        for ((a, b) in segments) {
            val d = distanceToSegment(point, a, b)
            if (d < best) best = d
        }
        return best
    }

    /** How far [point] sits from the nearest stroke in [outlines]; [Float.MAX_VALUE] if there are none. */
    fun distanceToNearestLine(point: Point, outlines: List<ColoringOutline>): Float {
        val segments = outlines.flatMap(::segmentsOf)
        if (segments.isEmpty()) return Float.MAX_VALUE
        return minDistanceToSegments(point, segments)
    }

    /**
     * True when [point] is inside [boundary] and isn't claimed by any region in
     * [smallerBoundaries] - the same "smallest enclosing region wins" rule
     * [ColoringViewModel]'s tap handling uses, so a label is never printed where tapping it
     * would actually color a different, overlapping region.
     */
    private fun isOwned(point: Point, boundary: List<Point>, smallerBoundaries: List<List<Point>>): Boolean {
        if (!PointInPolygon.contains(point, boundary)) return false
        return smallerBoundaries.none { PointInPolygon.contains(point, it) }
    }

    /**
     * The point inside [boundary] that the region actually owns (see [isOwned]) and that sits
     * farthest from every line in [avoidSegments] - the page's drawn strokes *plus* the edges of
     * every smaller overlapping region, so the anchor doesn't just barely cross into owned
     * territory but gets real breathing room from the line that divides it from a neighbor
     * (drawn or not). Falls back to the centroid if nothing better qualifies.
     */
    private fun anchorFor(
        boundary: List<Point>,
        avoidSegments: List<Pair<Point, Point>>,
        smallerBoundaries: List<List<Point>>
    ): Point {
        val centroid = centroidOf(boundary)
        if (avoidSegments.isEmpty() && smallerBoundaries.isEmpty()) return centroid

        val minX = boundary.minOf { it.x }
        val maxX = boundary.maxOf { it.x }
        val minY = boundary.minOf { it.y }
        val maxY = boundary.maxOf { it.y }

        var best: Point? = null
        var bestScore = -1f
        if (isOwned(centroid, boundary, smallerBoundaries)) {
            best = centroid
            bestScore = minDistanceToSegments(centroid, avoidSegments)
        }

        for (i in 0..ANCHOR_GRID_STEPS) {
            val x = minX + (maxX - minX) * (i.toFloat() / ANCHOR_GRID_STEPS)
            for (j in 0..ANCHOR_GRID_STEPS) {
                val y = minY + (maxY - minY) * (j.toFloat() / ANCHOR_GRID_STEPS)
                val candidate = Point(x, y)
                if (!isOwned(candidate, boundary, smallerBoundaries)) continue
                val score = minDistanceToSegments(candidate, avoidSegments)
                if (score > bestScore) {
                    bestScore = score
                    best = candidate
                }
            }
        }
        // Nothing on the grid was owned territory (an unusual shape almost entirely covered by
        // smaller siblings) - the centroid is the best any approach can do.
        return best ?: centroid
    }

    /**
     * Every region's label point for [regions] (all regions on one page), keyed by region id.
     * [outlines] are the page's drawn strokes (region boundaries plus any decorative detail
     * lines); pass them so labels avoid printing on top of ink, not just on top of each other.
     */
    fun computeLabelPoints(
        regions: List<ColoringRegion>,
        outlines: List<ColoringOutline> = emptyList()
    ): Map<String, Point> {
        if (regions.isEmpty()) return emptyMap()

        val lineSegments = outlines.flatMap(::segmentsOf)

        // The tap handler fills the *smallest* region containing the tapped point when regions
        // overlap, so a label can only safely sit where no smaller region also claims the spot.
        val areas = regions.associate { it.id to PointInPolygon.calculateArea(it.boundaryPoints) }
        fun smallerBoundariesFor(region: ColoringRegion): List<List<Point>> {
            val ownArea = areas.getValue(region.id)
            return regions.filter { it.id != region.id && areas.getValue(it.id) < ownArea }
                .map { it.boundaryPoints }
        }

        if (regions.size == 1) {
            val only = regions[0]
            return mapOf(only.id to anchorFor(only.boundaryPoints, lineSegments, emptyList()))
        }

        val smallerBoundariesByRegion = regions.map { smallerBoundariesFor(it) }
        val avoidSegmentsByRegion = smallerBoundariesByRegion.map { smallerBoundaries ->
            lineSegments + smallerBoundaries.flatMap(::polygonSegments)
        }
        val anchors = regions.mapIndexed { index, region ->
            anchorFor(region.boundaryPoints, avoidSegmentsByRegion[index], smallerBoundariesByRegion[index])
        }
        val positions = anchors.mapIndexed { index, c ->
            val angle = index * GOLDEN_ANGLE_RADIANS
            Point(
                x = c.x + cos(angle) * TIE_BREAK_NUDGE,
                y = c.y + sin(angle) * TIE_BREAK_NUDGE
            )
        }.toMutableList()

        repeat(ITERATIONS) {
            for (i in regions.indices) {
                for (j in i + 1 until regions.size) {
                    val a = positions[i]
                    val b = positions[j]
                    val d = distance(a, b)
                    if (d < MIN_SEPARATION && d > 0.00001f) {
                        val push = (MIN_SEPARATION - d) / 2f
                        val dx = (a.x - b.x) / d
                        val dy = (a.y - b.y) / d
                        positions[i] = Point(a.x + dx * push, a.y + dy * push)
                        positions[j] = Point(b.x - dx * push, b.y - dy * push)
                    }
                }
            }
        }

        return regions.indices.associate { i ->
            val boundary = regions[i].boundaryPoints
            val settled = clampInside(positions[i], anchors[i], boundary, avoidSegmentsByRegion[i], smallerBoundariesByRegion[i])
            regions[i].id to settled
        }
    }

    /**
     * A point that the region owns (see [isOwned]) and that also clears every line in
     * [avoidSegments] by [MIN_LINE_DISTANCE], as close to the relaxed [target] as possible,
     * falling back step by step toward [anchor] (which already satisfies both as well as that
     * shape allows).
     */
    private fun clampInside(
        target: Point,
        anchor: Point,
        boundary: List<Point>,
        avoidSegments: List<Pair<Point, Point>>,
        smallerBoundaries: List<List<Point>>
    ): Point {
        fun clearsLines(p: Point) =
            avoidSegments.isEmpty() || minDistanceToSegments(p, avoidSegments) >= MIN_LINE_DISTANCE
        fun owned(p: Point) = isOwned(p, boundary, smallerBoundaries)

        if (owned(target) && clearsLines(target)) return target
        for (t in CLAMP_STEPS) {
            val candidate = Point(
                x = anchor.x + (target.x - anchor.x) * t,
                y = anchor.y + (target.y - anchor.y) * t
            )
            if (owned(candidate) && clearsLines(candidate)) return candidate
        }

        // Nothing clears the lines by the full margin (a sliver of a shape, or ink on every
        // side) - settle for anything still owned by this region, favoring the anchor itself.
        if (owned(target)) return target
        for (t in CLAMP_STEPS) {
            val candidate = Point(
                x = anchor.x + (target.x - anchor.x) * t,
                y = anchor.y + (target.y - anchor.y) * t
            )
            if (owned(candidate)) return candidate
        }
        return anchor
    }

    private val CLAMP_STEPS = floatArrayOf(0.9f, 0.75f, 0.6f, 0.45f, 0.3f, 0.15f)
}
