    private val defaultCategoryMap: Map<String, DoodleCategory> = CATEGORIES.associateBy { it.id }

    fun findById(id: String): DoodleCategory {
        val normalizedId = id.trim().lowercase().replace(" ", "_").replace("-", "_")
        return defaultCategoryMap[normalizedId] ?: createFromRawLabel(id)
    }

    /**
     * Converts a raw label string (e.g. "The Eiffel Tower" or "coffee cup")
     * into a strongly typed [DoodleCategory] with appropriate emoji and title.
     */
    fun createFromRawLabel(rawLabel: String): DoodleCategory {
        val trimmed = rawLabel.trim()
        val id = trimmed.lowercase().replace(" ", "_").replace("-", "_")

        val emoji = EMOJI_MAP[id] ?: "🎨"

        val displayName = when {
            trimmed.startsWith("The ", ignoreCase = true) -> {
                // "The Eiffel Tower" -> "Eiffel Tower"
                trimmed.substring(4).split(" ")
                    .joinToString(" ") { it.replaceFirstChar { c -> c.uppercase() } }
            }
            else -> {
                trimmed.split(" ")
                    .joinToString(" ") { word ->
                        word.replaceFirstChar { if (it.isLowerCase()) it.titlecase() else it.toString() }
                    }
            }
        }

        return DoodleCategory(id = id, displayName = displayName, emoji = emoji)
    }

    /**
     * Converts a list of line-separated class labels from the model's `labels.txt`
     * into an ordered list of [DoodleCategory] items corresponding directly to model output indices.
     */
    fun fromLabels(labels: List<String>): List<DoodleCategory> {
        return labels.map { label -> createFromRawLabel(label) }
    }
